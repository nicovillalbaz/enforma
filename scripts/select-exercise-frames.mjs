// Pick the two most distinct poses from each normalized three-frame sequence.
// Review overrides are kept explicit when artwork thickness otherwise dominates the comparison.
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import sharp from 'sharp';
import { exerciseArtworkSlugs } from '../apps/web/src/exercise-artwork.ts';

const sourceRoot = resolve('apps/web/public/exercise-art');
const overrides = {
  'bench-press': [1, 3],
  'dumbbell-bench-press': [1, 2],
  'incline-bench-press': [1, 3],
  'incline-dumbbell-press': [1, 3],
  'machine-chest-press': [1, 3],
  'goblet-squat': [1, 3],
  'lat-pulldown': [1, 3],
  'leg-press': [1, 3],
  'push-up': [1, 3],
  deadlift: [1, 3],
  'romanian-deadlift': [1, 3],
  'sumo-deadlift': [1, 3],
  'reverse-lunge': [1, 3],
  'step-up': [1, 3],
  'standing-dumbbell-press': [1, 3],
  'machine-shoulder-press': [1, 3],
  'cable-lateral-raise': [1, 3],
  elliptical: [1, 2],
  'jump-rope': [1, 2],
  'banded-row': [1, 3],
};
const pairs = [
  [1, 2],
  [1, 3],
  [2, 3],
];
const chosen = {};
const audit = [];

for (const slug of exerciseArtworkSlugs) {
  const images = await Promise.all(
    [1, 2, 3].map(async (frame) => {
      const svg = await readFile(resolve(sourceRoot, slug, `frame-${frame}.svg`));
      return sharp(svg)
        .resize(128, 128)
        .flatten({ background: '#fff' })
        .grayscale()
        .blur(1.2)
        .raw()
        .toBuffer();
    }),
  );
  const distances = pairs.map(([a, b]) => {
    let total = 0;
    for (let i = 0; i < images[a - 1].length; i++)
      total += Math.abs(images[a - 1][i] - images[b - 1][i]);
    return Number((total / images[a - 1].length).toFixed(2));
  });
  const maximum = distances.indexOf(Math.max(...distances));
  chosen[slug] = overrides[slug] ?? pairs[maximum];
  audit.push({ slug, distances, selected: chosen[slug], reviewed: Boolean(overrides[slug]) });
}
const entries = Object.entries(chosen)
  .map(([slug, pair]) => `  '${slug}': [${pair.join(', ')}],`)
  .join('\n');
await writeFile(
  'apps/web/src/exercise-frame-pairs.ts',
  `// Two clear postures per exercise, selected from the local normalized artwork.\n// Generated by scripts/select-exercise-frames.mjs; reviewed overrides live in that script.\nexport const exerciseFramePairs: Record<string, readonly [number, number]> = {\n${entries}\n};\n`,
);
await writeFile(
  'docs/evidencias/exercise-frame-selection.json',
  JSON.stringify(audit, null, 2) + '\n',
);
console.info(`Selected two poses for ${audit.length} exercises.`);
